import type { Column, Row } from './reports';

/** Plain value for a cell: money as pesos with centavos, everything else as is. */
function cellValue(col: Column, v: Row[string]): string | number | null {
  if (v === null || v === undefined) return null;
  if (col.type === 'money') return Number(v) / 100;
  return v;
}

/** Byte-order mark, so Excel reads the CSV as UTF-8. */
export const BOM = String.fromCharCode(0xfeff);

export function toCsv(columns: readonly Column[], rows: readonly Row[]): string {
  const esc = (v: string | number | null) => {
    const s = v === null ? '' : typeof v === 'number' ? String(v) : v;
    return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const lines = [columns.map((c) => esc(c.label)).join(','), ...rows.map((r) => columns.map((c) => esc(cellValue(c, r[c.key] ?? null))).join(','))];
  return `${BOM}${lines.join('\r\n')}\r\n`;
}

